"""Regenerate docs/io_map.md from the ST declarations.

The address map has exactly one source of truth -- the AT clauses in
GVL_Io.st -- and this renders it into a table. CI runs it with --check, so a
tag added to the ST without regenerating the document fails the build rather
than quietly leaving the documentation wrong.

    python scripts/render_io_map.py
    python scripts/render_io_map.py --check
"""

from __future__ import annotations

import argparse
import os
import re
import sys
from typing import Dict, List, Tuple

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

from src.harness.cell import PLC_DIR, PROGRAM_ORDER  # noqa: E402
from src.harness.io_map import build_io_map  # noqa: E402
from src.iec61131.runtime import load  # noqa: E402

REPO_ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
TARGET = os.path.join(REPO_ROOT, "docs", "io_map.md")

HEADER = """# I/O map

Generated by `scripts/render_io_map.py` from the `AT` clauses in
[plc/types/GVL_Io.st](../plc/types/GVL_Io.st). Do not edit by hand: CI checks
that this file matches the ST.

Address convention:

| Form | Meaning |
| --- | --- |
| `%IXb.i` | input bit `i` of byte `b` |
| `%QXb.i` | output bit |
| `%MXb.i` | memory bit, readable and writable by a SCADA client |
| `%IDn` / `%QDn` / `%MDn` | double word `n`, holding one REAL |
| `%MWn` | memory word `n`, holding one INT |

Modbus placement, as implemented in `src/harness/io_map.py`:

| Area | Modbus table | Address |
| --- | --- | --- |
| `%IXb.i` | discrete input | `b*8 + i` |
| `%QXb.i` | coil | `b*8 + i` |
| `%MXb.i` | coil | `1000 + b*8 + i` |
| `%IDn` | input registers | `2n`, `2n+1` |
| `%QDn` | holding registers | `2n`, `2n+1` |
| `%MWn` | holding register | `1000 + n` |
| `%MDn` | holding registers | `2000 + 2n`, `+1` |

REALs are IEEE 754 single precision, high word first. Only the `%M` area is
writable by a client; writing a `%Q` point would be overwritten by the next
scan, so the server rejects it.
"""

SECTIONS = [
    ("Digital inputs", lambda p: p.address.prefix == "I" and p.address.is_bit),
    ("Analogue inputs", lambda p: p.address.prefix == "I" and not p.address.is_bit),
    ("Digital outputs", lambda p: p.address.prefix == "Q" and p.address.is_bit),
    ("Analogue outputs", lambda p: p.address.prefix == "Q" and not p.address.is_bit),
    ("Memory: commands and status", lambda p: p.address.prefix == "M"),
]


DECLARATION = re.compile(
    r"^\s*([A-Za-z_]\w*)\s+AT\s+(%[A-Za-z0-9.]+)\s*:\s*[A-Za-z_]\w*\s*;"
    r"[ 	]*(?:\(\*(.*?)\*\))?[ 	]*$"
)


def read_declarations(path: str) -> Dict[str, Tuple[str, str]]:
    r"""Original spelling and trailing comment for each located variable.

    Matched a line at a time on purpose: an ^...$ pattern with re.MULTILINE and
    a leading \s* will happily run across a newline and pick up the next
    declaration's comment.
    """
    found: Dict[str, Tuple[str, str]] = {}
    with open(path, "r", encoding="utf-8") as handle:
        for line in handle:
            match = DECLARATION.match(line.rstrip())
            if match:
                found[match.group(1).upper()] = (match.group(1), (match.group(3) or "").strip())
    return found


def render() -> str:
    runtime = load(PLC_DIR, PROGRAM_ORDER)
    io_map = build_io_map(runtime)
    declarations = read_declarations(os.path.join(PLC_DIR, "types", "GVL_Io.st"))

    lines: List[str] = [HEADER, ""]
    lines.append("{0} located variables in total.".format(len(io_map.points)))
    lines.append("")
    for heading, predicate in SECTIONS:
        points = sorted(
            [p for p in io_map.points if predicate(p)],
            key=lambda p: (p.address.word, p.address.bit),
        )
        if not points:
            continue
        lines.append("## {0}".format(heading))
        lines.append("")
        lines.append("| Tag | Address | Type | Modbus | Notes |")
        lines.append("| --- | --- | --- | --- | --- |")
        for point in points:
            source_name, comment = declarations.get(point.name, (point.name, ""))
            registers = (
                "{0} {1}-{2}".format(point.table, point.offset, point.offset + 1)
                if point.words == 2
                else "{0} {1}".format(point.table, point.offset)
            )
            lines.append(
                "| `{0}` | `{1}` | {2} | {3} | {4} |".format(
                    source_name,
                    point.address.text,
                    point.type_name,
                    registers,
                    comment,
                )
            )
        lines.append("")
    return "\n".join(lines).rstrip() + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail if the file is out of date")
    args = parser.parse_args()

    rendered = render()
    if args.check:
        if not os.path.exists(TARGET):
            print("docs/io_map.md is missing; run scripts/render_io_map.py")
            return 1
        with open(TARGET, "r", encoding="utf-8") as handle:
            current = handle.read()
        if current != rendered:
            print("docs/io_map.md is out of date; run scripts/render_io_map.py")
            return 1
        print("docs/io_map.md matches the ST declarations")
        return 0

    os.makedirs(os.path.dirname(TARGET), exist_ok=True)
    with open(TARGET, "w", encoding="utf-8") as handle:
        handle.write(rendered)
    print("wrote", os.path.relpath(TARGET, REPO_ROOT))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
